#[test]
fn the_candidate_is_loadable_and_is_not_the_baseline() {
    let Some((_hold, binary)) = prepared() else {
        eprintln!("skipping: cargo unavailable");
        return;
    };
    let workspace = Workspace::new();
    workspace.write_baseline();

    let content = b"A long enough memory to train on. ";
    let record = workspace.store_memory(content);
    let manifest = workspace.manifest(&[(record, sha256_hex(content))]);

    let candidate = workspace.directory.join("candidate");
    let Some(output) = consolidate(&binary, &workspace.checkpoint, &candidate, &manifest) else { return; };
    assert!(output.status.success());

    // Both load, so the dream gate can digest and compare them.
    let baseline = pmc_train::checkpoint::load(&workspace.checkpoint).expect("load baseline");
    let trained = pmc_train::checkpoint::load(&candidate).expect("load candidate");
    assert_eq!(baseline.config, trained.config, "the architecture changed");

    // And they are different models: SPIN moved the parameters. If they were
    // identical, the "consolidation" would be an identity, and the gate would
    // have nothing to measure.
    let before = baseline.to_bytes();
    let after = trained.to_bytes();
    assert_ne!(before, after, "the candidate is byte-identical to the baseline");
    assert_eq!(before.len(), after.len(), "the parameter count changed");
}

