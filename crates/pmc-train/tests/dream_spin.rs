#[test]
fn a_well_formed_replay_consolidates_and_writes_a_candidate() {
    let Some((_hold, binary)) = prepared() else {
        eprintln!("skipping: cargo unavailable");
        return;
    };
    let workspace = Workspace::new();
    workspace.write_baseline();

    let first = workspace.store_memory(b"The gate code is 47-rosso. Memory persists.");
    let second = workspace.store_memory(b"Dreams consolidate what matters.");
    let manifest = workspace.manifest(&[
        (first.clone(), sha256_hex(b"The gate code is 47-rosso. Memory persists.")),
        (second.clone(), sha256_hex(b"Dreams consolidate what matters.")),
    ]);

    let candidate = workspace.directory.join("candidate");
    let Some(output) = consolidate(&binary, &workspace.checkpoint, &candidate, &manifest) else { return; };
    let stderr = String::from_utf8_lossy(&output.stderr).to_string();
    assert!(output.status.success(), "the consolidator failed: {stderr}");

    // The candidate is written in the format the baseline was read in, so the
    // dream gate can digest it and roll back to it byte for byte.
    assert!(candidate.join("checkpoint.bin").is_file(), "no checkpoint.bin");
    assert!(candidate.join("manifest.json").is_file(), "no manifest.json");

    // The report carries the record ids, so a negative result is attributable.
    let stdout = String::from_utf8_lossy(&output.stdout).to_string();
    assert!(stdout.contains("pmc-dream-spin/1"), "no report schema: {stdout}");
    assert!(stdout.contains(&first), "the report omits a replayed record: {stdout}");
    assert!(
        stdout.contains("Spin".to_lowercase().as_str())
            || stdout.contains("spin"),
        "the report does not name the mechanism: {stdout}"
    );
}

#[test]
fn a_manifest_without_an_items_array_is_refused() {
    let Some((_hold, binary)) = prepared() else {
        eprintln!("skipping: cargo unavailable");
        return;
    };
    let workspace = Workspace::new();
    workspace.write_baseline();

    let path = workspace.directory.join("bad.json");
    fs::write(&path, b"{\"records\":[]}").expect("write a malformed manifest");

    let candidate = workspace.directory.join("candidate");
    let Some(output) = consolidate(&binary, &workspace.checkpoint, &candidate, &path) else { return; };
    assert!(!output.status.success(), "a wrong-shaped manifest was accepted");
    let stderr = String::from_utf8_lossy(&output.stderr).to_string();
    assert!(
        stderr.contains("items"),
        "the refusal should name what was missing: {stderr}"
    );
    assert!(
        !candidate.exists(),
        "no candidate may be written from a refused dream"
    );
}

