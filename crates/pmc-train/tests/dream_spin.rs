static TEMP_COUNTER: AtomicU64 = AtomicU64::new(0);

struct TempDir {
    path: PathBuf,
}

impl TempDir {
    fn new(tag: &str) -> Self {
        let mut path = std::env::temp_dir();
        path.push(format!(
            "pmc-dream-spin-{}-{}-{}",
            std::process::id(),
            TEMP_COUNTER.fetch_add(1, Ordering::Relaxed),
            tag
        ));
        fs::create_dir_all(&path).expect("create temporary directory");
        TempDir { path }
    }

    fn join(&self, name: &str) -> PathBuf {
        self.path.join(name)
    }
}

impl Drop for TempDir {
    fn drop(&mut self) {
        let _ = fs::remove_dir_all(&self.path);
    }
}

/// A small, valid transformer config: the point is the interface, not size.
fn small_config() -> TransformerConfig {
    TransformerConfig {
        n_layer: 2,
        d_model: 16,
        n_head: 2,
        ffn_hidden: 32,
        vocab: 64,
        n_positions: 32,
        readout_rank: 8,
    }
}

/// A workspace laid out the way a dream runs it: `<ws>/checkpoint/` and
/// `<ws>/sidecar/private/`.
struct Workspace {
    directory: TempDir,
    checkpoint: PathBuf,
    private: PathBuf,
}

impl Workspace {
    fn new() -> Self {
        let directory = TempDir::new("ws");
        let checkpoint = directory.join("checkpoint");
        let private = directory.join("sidecar").join("private");
        fs::create_dir_all(&private).expect("create private store");
        Workspace {
            directory,
            checkpoint,
            private,
        }
    }

    /// Write a baseline checkpoint the trainer can read back.
    fn write_baseline(&self) {
        let model = small_config().init(20261031);
        save(&self.checkpoint, &model).expect("write baseline checkpoint");
    }

    /// Write a memory into the private store, in the layout
    /// `pmc.dignity.private_store` uses, and return its record id.
    ///
    /// The blob path hashes the canonical JSON encoding of the key - the quoted
    /// string - not the key's raw bytes. Getting this wrong yields a valid but
    /// empty store, so the test mirrors the Python store exactly rather than
    /// the Rust module's own assumption.
    fn store_memory(&self, content: &[u8]) -> String {
        let record_id = format!("mem_{}", &sha256_hex(content)[..16]);
        let mut quoted = String::with_capacity(record_id.len() + 2);
        quoted.push('"');
        quoted.push_str(&record_id);
        quoted.push('"');
        let key = sha256_hex(quoted.as_bytes());
        let mut file = File::create(self.private.join(format!("{}.bin", &key[..32])))
            .expect("create a private store blob");
        file.write_all(content).expect("write a private store blob");
        record_id
    }

    fn manifest(&self, items: &[(String, String)]) -> PathBuf {
        let rows: Vec<String> = items
            .iter()
            .map(|(id, digest)| {
                format!(
                    "{{\"record_id\":\"{}\",\"content_digest\":\"{}\",\"emotional_load\":0.5}}",
                    id, digest
                )
            })
            .collect();
        let path = self.directory.join("replay.json");
        let mut file = File::create(&path).expect("create the replay manifest");
        write!(
            file,
            "{{\"items\":[{}]}}",
            rows.join(",")
        )
        .expect("write the replay manifest");
        path
    }
}

/// Run the consolidator, or skip the calling test when it cannot be built.
///
/// Returns `None` when cargo is absent. A test that gets `None` returns
/// immediately, which is how a Rust test skips. It does **not** call
/// `std::process::exit`: that terminates the whole test binary, so libtest
/// prints "running N tests" and then nothing at all - which looks like a
/// clean run and is the exact silent-skip failure this repository's own parity
/// tests were written to prevent.
fn consolidate(
    binary: &Path,
    baseline: &Path,
    candidate: &Path,
    manifest: &Path,
) -> Option<std::process::Output> {
    Command::new(binary)
        .arg(baseline)
        .arg(candidate)
        .arg(manifest)
        .env("PMC_STEPS", "3")
        .output()
        .ok()
}

/// Build the consolidator binary once, or skip.
///
/// The build is cached by cargo, so calling this per test is cheap.
fn prepared() -> Option<(TempDir, PathBuf)> {
    // A holder that keeps the built binary reachable for the test's lifetime.
    let Some(binary) = consolidator_binary() else {
        return None;
    };
    Some((TempDir::new("hold"), binary))
}

