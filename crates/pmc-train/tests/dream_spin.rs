#[test]
fn a_null_load_is_not_a_load_of_zero() {
    let Some((_hold, binary)) = prepared() else {
        eprintln!("skipping: cargo unavailable");
        return;
    };
    let workspace = Workspace::new();
    workspace.write_baseline();
    let record = workspace.store_memory(b"A memory whose load was never recorded.");

    let path = workspace.directory.join("null-load.json");
    fs::write(
        &path,
        format!(
            "{{\"items\":[{{\"record_id\":\"{record}\",\"content_digest\":\"{}\",\"emotional_load\":null}}]}}",
            sha256_hex(b"A memory whose load was never recorded.")
        ),
    )
    .expect("write a manifest with a null load");

    let candidate = workspace.directory.join("candidate");
    let Some(output) = consolidate(&binary, &workspace.checkpoint, &candidate, &path) else { return; };
    // A null load is "not recorded": the dream still runs, with that memory
    // ordered by its other keys rather than by a load of zero pretending to be
    // a measurement.
    assert!(
        output.status.success(),
        "a null load should not stop the dream: {}",
        String::from_utf8_lossy(&output.stderr)
    );
}

