//! Integration tests for `dream_spin`, the PMC dream cycle's SPIN consolidator.
//!
//! The consolidator is the interface the dream pipeline calls:
//! `<baseline> <candidate> <replay_manifest>`. What matters about it is that
//! the training signal is **self-play and not supervised**, and that it runs
//! against the real checkpoint format. These tests check the parts that can be
//! checked without a GPU or a GGUF:
//!
//! * the replay manifest is parsed as the *pipeline's* contract, and a
//!   manifest that is not that contract is refused rather than guessed at;
//! * the chosen side comes from the replayed memories, and the rejected side
//!   is generated by the model being trained - which is what makes it SPIN;
//! * a truncated or mismatched store is survived, not crashed on;
//! * the candidate is written in the format the baseline was read in.
//!
//! No model is loaded: the checkpoint is one the test writes itself with the
//! trainer's own writer, so a failing test means the consolidator changed, not
//! that a file went missing.

use std::fs::{self, File};
use std::io::Write;
use std::path::{Path, PathBuf};
use std::process::Command;
use std::sync::atomic::{AtomicU64, Ordering};

use pmc_core::sha256_hex;
use pmc_train::checkpoint::{save, save_with_step};
use pmc_train::transformer::TransformerConfig;

/// The consolidator binary, built once for this test run.
///
/// Built by cargo rather than assumed present, and skipped cleanly when cargo
/// is unavailable: a skip that names its reason is honest, and one that fails
/// on a machine without a toolchain is not.
fn consolidator_binary() -> Option<PathBuf> {
    let cargo = resolve_cargo()?;
    let crate_dir = Path::new(env!("CARGO_MANIFEST_DIR"));
    let built = Command::new(&cargo)
        .arg("build")
        .arg("--offline")
        .arg("--release")
        .arg("--example")
        .arg("dream_spin")
        .current_dir(crate_dir)
        .output()
        .expect("run cargo build");
    if !built.status.success() {
        panic!(
            "cargo build failed: {}",
            String::from_utf8_lossy(&built.stderr)
        );
    }
    let binary = crate_dir
        .join("target")
        .join("release")
        .join("examples")
        .join("dream_spin.exe");
    binary.is_file().then_some(binary)
}

fn resolve_cargo() -> Option<PathBuf> {
    if let Some(found) = which("cargo") {
        return Some(found);
    }
    // On Windows cargo lives in the rustup home and is not on PATH for every
    // shell, which is how the parity tests came to skip silently. Checking the
    // rustup home as well is the difference between a skip and a lie.
    let home = std::env::var_os("USERPROFILE").map(PathBuf::from)?;
    for name in ["cargo", "cargo.exe"] {
        let candidate = home.join(".cargo").join("bin").join(name);
        if candidate.is_file() {
            return Some(candidate);
        }
    }
    None
}

fn which(name: &str) -> Option<PathBuf> {
    let paths = std::env::var_os("PATH")?;
    for directory in std::env::split_paths(&paths) {
        for suffix in ["", ".exe"] {
            let candidate = directory.join(format!("{name}{suffix}"));
            if candidate.is_file() {
                return Some(candidate);
            }
        }
    }
    None
}

