#[test]
fn the_same_inputs_produce_the_same_candidate() {
    let Some((_hold, binary)) = prepared() else {
        eprintln!("skipping: cargo unavailable");
        return;
    };
    // Reproducibility is the property that makes a consolidation a measurement
    // rather than a run: the embedding is derived from the baseline's own
    // bytes, so the only inputs are the two files.
    let first = Workspace::new();
    first.write_baseline();
    let content = b"A memory, with content worth consolidating. ";
    let record = first.store_memory(content);
    let manifest = first.manifest(&[(record, sha256_hex(content))]);
    let candidate = first.directory.join("candidate");
    assert!(consolidate(&binary, &first.checkpoint, &candidate, &manifest).expect("run the first candidate").status.success());

    let second = Workspace::new();
    second.write_baseline();
    let record = second.store_memory(content);
    let manifest = second.manifest(&[(record, sha256_hex(content))]);
    let other = second.directory.join("candidate");
    assert!(consolidate(&binary, &second.checkpoint, &other, &manifest).expect("run the second candidate").status.success());

    assert_eq!(
        fs::read(candidate.join("checkpoint.bin")).expect("read the first candidate"),
        fs::read(other.join("checkpoint.bin")).expect("read the second candidate"),
        "two runs over identical inputs produced different candidates"
    );
}

#[test]
fn the_blob_path_matches_the_python_store_exactly() {
    // The layout is mirrored across two languages, and a mirrored hash is a
    // place a port can silently diverge: both sides compute a valid SHA-256, so
    // nothing fails until a real store yields an empty replay. The expected
    // name below is what `pmc.dignity.private_store` writes for this record id,
    // so this test fails if either side drifts.
    let record_id = "mem_9db0ad28d49c6324";
    let mut quoted = String::with_capacity(record_id.len() + 2);
    quoted.push('"');
    quoted.push_str(record_id);
    quoted.push('"');
    let key = sha256_hex(quoted.as_bytes());
    let blob = PathBuf::from(format!("{}.bin", &key[..32]));

    assert_eq!(
        blob.file_name().and_then(|name| name.to_str()),
        Some("04ce181b3676467e16bcacfb761d866a.bin"),
        "the Rust blob path and the Python private store have diverged"
    );

    // And the raw-bytes form is *different*, which is the divergence to avoid.
    let raw = sha256_hex(record_id.as_bytes());
    assert_ne!(&raw[..32], &key[..32], "raw-bytes hashing would look right");
}

#[test]
fn a_checkpoint_written_with_a_step_is_still_readable() {
    let Some((_hold, binary)) = prepared() else {
        eprintln!("skipping: cargo unavailable");
        return;
    };
    // The baseline a dream runs against is whatever the last committed dream
    // left, including one whose manifest records a step. Reading it must not
    // depend on that field being zero.
    let directory = TempDir::new("stepped");
    let checkpoint = directory.join("checkpoint");
    let model = small_config().init(20261031);
    save_with_step(&checkpoint, &model, 41).expect("write a stepped checkpoint");

    let private = directory.join("sidecar").join("private");
    fs::create_dir_all(&private).expect("create a private store");
    let content = b"A memory to consolidate after a previous dream. ";
    let record_id = format!("mem_{}", &sha256_hex(content)[..16]);
    let mut quoted = String::with_capacity(record_id.len() + 2);
    quoted.push('"');
    quoted.push_str(&record_id);
    quoted.push('"');
    let key = sha256_hex(quoted.as_bytes());
    fs::write(
        private.join(format!("{}.bin", &key[..32])),
        content,
    )
    .expect("write a private store blob");
    let manifest = directory.join("replay.json");
    fs::write(
        &manifest,
        format!(
            "{{\"items\":[{{\"record_id\":\"{}\",\"content_digest\":\"{}\",\"emotional_load\":0.5}}]}}",
            record_id,
            sha256_hex(content)
        ),
    )
    .expect("write a manifest");

    let candidate = directory.join("candidate");
    let Some(output) = consolidate(&binary, &checkpoint, &candidate, &manifest) else { return; };
    assert!(
        output.status.success(),
        "a stepped baseline was refused: {}",
        String::from_utf8_lossy(&output.stderr)
    );
}
